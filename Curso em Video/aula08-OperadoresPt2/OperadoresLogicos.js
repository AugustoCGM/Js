// Operadores Lógicos em JavaScript

// 1. Negação (!): Inverte o valor booleano (Not)
// Exemplo: !true vira false, !false vira true

// 2. Conjunção (&&): Retorna true apenas se AMBOS forem verdadeiros (And)
// Exemplo: (true && true) -> true
//          (true && false) -> false

// 3. Disjunção (||): Retorna true se PELO MENOS UM for verdadeiro (Or)
// Exemplo: (true || false) -> true
//          (false || false) -> false

/*
Ordem de Precedência (regra para expressões complexas):
1º: Negação (!)
2º: Conjunção (&&)
3º: Disjunção (||)
*/