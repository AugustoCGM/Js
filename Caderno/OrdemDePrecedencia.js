// Ordem de Precedência em JavaScript

// 1º: Parênteses ( ) - Têm a maior prioridade
// 2º: Potência (**)
// 3º: Multiplicação (*), Divisão (/), Resto da Divisão (%)
// 4º: Adição (+), Subtração (-)

// Exemplo prático de aplicação:
let calculo = 5 + 3 / 2;      // Primeiro faz 3/2 (1.5), depois 5 + 1.5 = 6.5
let comPrecedencia = (5 + 3) / 2; // Primeiro faz (5+3) = 8, depois 8 / 2 = 4